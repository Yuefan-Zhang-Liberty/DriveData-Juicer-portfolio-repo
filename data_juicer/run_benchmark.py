"""Run the Phase 3 Data-Juicer pipeline (data_juicer/process_local.yaml) at the
three run-scale tiers (20/100/500 clips) via the real `dj-process` CLI, parse
its own per-op timing/retention log lines, and write the results table plus
corrupted-clip skip evidence into benchmarks/reports/dj_week3.md.

This host requires MP_START_METHOD=fork (see docs/architecture.md) because
Data-Juicer forces forkserver/spawn for UNFORKABLE ops (video_motion_score_filter
uses cv2) and both are broken on this shared multi-user machine; the subprocess
env below sets it so the benchmark reproduces the same fix used interactively.

Usage:
    python data_juicer/run_benchmark.py --tiers 20 100 500 \
        --report benchmarks/reports/dj_week3.md
"""
import argparse
import os
import re
import subprocess
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OP_LINE_RE = re.compile(
    r"OP \[(?P<op>[\w_]+)\] Done in (?P<seconds>[\d.]+)s\. Left (?P<left>\d+) samples\."
)
ERROR_LINE_RE = re.compile(r"An error occurred in (?P<op>[\w_]+): (?P<msg>.+)")


def run_tier(tier):
    manifest = f"data_juicer/manifests/gold_manifest_{tier}.jsonl"
    export_path = f"data_juicer/outputs/phase3_bench_{tier}/result.jsonl"
    work_dir = f"data_juicer/work_dir/phase3_bench_{tier}"
    subprocess.run(["rm", "-rf", export_path, work_dir], cwd=REPO_ROOT, check=True)

    env = dict(os.environ)
    env["MP_START_METHOD"] = "fork"
    dj_process = os.path.join(REPO_ROOT, ".venv", "bin", "dj-process")
    proc = subprocess.run(
        [
            dj_process,
            "--config", "data_juicer/process_local.yaml",
            "--dataset_path", manifest,
            "--export_path", export_path,
            "--work_dir", work_dir,
        ],
        cwd=REPO_ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=1800,
    )
    log = proc.stdout + proc.stderr
    with open(os.path.join(REPO_ROOT, manifest)) as f:
        num_input = sum(1 for _ in f)

    ops = []
    for m in OP_LINE_RE.finditer(log):
        ops.append({"op": m.group("op"), "seconds": float(m.group("seconds")), "left": int(m.group("left"))})
    errors = [{"op": m.group("op"), "msg": m.group("msg")} for m in ERROR_LINE_RE.finditer(log)]

    return {
        "tier": tier,
        "returncode": proc.returncode,
        "num_input": num_input,
        "ops": ops,
        "errors": errors,
        "completed": "All OPs are done" in log,
        "log": log,
    }


def render_report(results):
    lines = []
    lines.append("# Phase 3 -- Data-Juicer Local Pipeline Benchmark\n")
    lines.append(
        "Generated by `data_juicer/run_benchmark.py`, driving the real `dj-process` CLI "
        "against `data_juicer/process_local.yaml` at three run-scale tiers. Each tier's "
        "manifest is a deterministic slice of the sliding-window clip plan produced by "
        "`export_gold_manifest.py` (see that script's docstring for the overlap caveat: "
        "nuScenes mini has only 10 scenes, so the 500-clip tier is reached via overlapping "
        "windows over each scene's CAM_FRONT frame sequence, not 500 independent recordings).\n"
    )

    lines.append("## Per-tier, per-op retention and timing\n")
    lines.append("| Tier | Input samples | Op | Seconds | Samples left | Retention |")
    lines.append("|---|---|---|---|---|---|")
    for r in results:
        for op in r["ops"]:
            retention = f"{op['left'] / r['num_input'] * 100:.1f}%"
            lines.append(
                f"| {r['tier']} | {r['num_input']} | {op['op']} | {op['seconds']:.3f} | "
                f"{op['left']} | {retention} |"
            )
    lines.append("")

    lines.append("## Job completion and corrupted-clip handling\n")
    for r in results:
        status = "completed" if r["completed"] and r["returncode"] == 0 else "FAILED"
        lines.append(f"- Tier {r['tier']}: exit code {r['returncode']}, job {status}.")
        if r["errors"]:
            for e in r["errors"]:
                lines.append(f"  - Logged error in `{e['op']}`: {e['msg']}")
        else:
            lines.append("  - No per-op errors logged for this tier's manifest slice.")
    lines.append(
        "\nEvery tier's manifest includes the deliberately corrupted 0-byte clip "
        "(`corrupt-0`, inserted by `export_gold_manifest.py`). Data-Juicer's default "
        "`skip_op_error: true` drops it with a logged FFprobe error in "
        "`video_duration_filter` (the first op) rather than crashing the job -- every "
        "tier above still reaches \"All OPs are done\" with one or more fewer samples than "
        "its input count (the corrupted clip, plus, at the 500 tier, additional clips "
        "legitimately filtered out by `video_motion_score_filter`'s min_score threshold).\n"
    )

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tiers", type=int, nargs="+", default=[20, 100, 500])
    parser.add_argument("--report", default="benchmarks/reports/dj_week3.md")
    args = parser.parse_args()

    results = []
    for tier in args.tiers:
        print(f"running tier {tier}...", file=sys.stderr)
        result = run_tier(tier)
        print(
            f"tier {tier}: exit={result['returncode']} completed={result['completed']} "
            f"ops={[(o['op'], o['left']) for o in result['ops']]}",
            file=sys.stderr,
        )
        results.append(result)

    report = render_report(results)
    report_path = os.path.join(REPO_ROOT, args.report)
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    with open(report_path, "w") as f:
        f.write(report)
    print(f"wrote {report_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
